/**
 * Сборка клиента — всегда production, что бы ни стояло в корневом `.env`.
 *
 * `.env` у монорепо один (docs/20-env-and-ports.md §1), и в нём
 * `NODE_ENV="development"` — для бэкенда. Vite читает эту переменную из того
 * же файла и штатно понимает её как «собери development»: в бандл уезжали
 * отладочные React и JSX с отладочной разметкой — вдвое тяжелее и медленнее, и
 * бюджет первой загрузки мерил не то, что получит игрок.
 *
 * Vite запоминает `NODE_ENV` из файла в `VITE_USER_NODE_ENV` и применяет его,
 * только если переменная ещё не задана. Пустое значение до загрузки окружения
 * означает «из файла не брать»; явный `NODE_ENV` в окружении процесса
 * по-прежнему главнее — так dev-сборку можно получить осознанно.
 *
 * Держится проверкой в `scripts/bundle-budget.mjs`: отладочный JSX в первой
 * загрузке роняет бюджет.
 */
export function ignoreDotenvNodeEnvForBuild(command: "build" | "serve"): void {
  if (command !== "build") return;
  process.env.VITE_USER_NODE_ENV ??= "";
}
