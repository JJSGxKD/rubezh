import { randomInt } from "node:crypto";

/**
 * `platformUserId` игрока для тестов: строка из 15 цифр, [10^14, 9·10^14).
 *
 * Все файлы одного прогона пишут в общую базу CI, и `upsert` по совпавшему
 * id молча возвращает уже заведённого игрока — чужого или своего. Случайное
 * число из сотен миллионов совпадало на тысячах игроков прогона и роняло тесты
 * не по делу. Здесь пространство — 8·10^14: между воркерами vitest совпадение
 * практически невозможно, а внутри одного процесса повтор исключён явно.
 * Пятнадцать цифр — предел, который сервер пускает к площадке как id игрока
 * (`PORT_USER_ID` в `bot-mention-rules.ts`); значение — безопасное целое JS, и
 * площадки, которые читают id числом, его не исказят; короткие фиксированные id
 * тестов («1», «42») с ним не пересекаются.
 */
const issued = new Set<string>();

export function uniquePlatformUserId(): string {
  for (;;) {
    // randomInt берёт диапазон не шире 2^48, поэтому число собрано из двух частей.
    const id = String(100_000_000_000_000 + randomInt(0, 800_000) * 1_000_000_000 + randomInt(0, 1_000_000_000));
    if (issued.has(id)) continue;
    issued.add(id);
    return id;
  }
}
