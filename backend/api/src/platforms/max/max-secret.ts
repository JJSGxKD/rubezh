/**
 * Секрет вебхука в том виде, в каком его принимает MAX и присылает обратно в
 * заголовке `X-Max-Bot-Api-Secret` (docs/35-stage4-plan.md Р188, tasks/T-0379).
 *
 * В описании поля `secret` у `POST /subscriptions` разрешены латиница, цифры и
 * дефис, а в шаблоне рядом — ещё и «_»; генератор ключей панели выдаёт base64url,
 * где «_» бывает. Чтобы не зависеть от того, какое из двух описаний верно,
 * подчёркивание заменяется дефисом: так секрет подходит под оба. И подписка,
 * и вебхук берут секрет только отсюда — иначе сверка не сошлась бы.
 */
export function maxSecretOf(stored: string): string {
  return stored.replaceAll("_", "-");
}
