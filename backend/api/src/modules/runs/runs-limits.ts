import type { RateLimit } from "../ingest/rate-limiter.js";

/**
 * Лимиты приёма забегов (docs/34-stage3-plan.md, WP4). Бизнес-параметры, а
 * не пороги антифрода: меняются здесь, в карте конфигурации —
 * docs/30-configuration-map.md.
 *
 * Лимит — по аккаунту, а не по адресу: за адресом мобильного оператора стоят
 * сотни игроков. 120 забегов в час — это забег каждые полминуты без
 * перерыва; живой игрок столько не сыграет, а скрипт, долбящий приём,
 * упрётся сюда.
 */
export const RUNS_LIMITS: Record<"start" | "finish" | "detail" | "adContinue" | "gemContinue" | "leaderboard" | "profile" | "proof", RateLimit> = {
  start: { scope: "runs:start", limit: 120, windowSec: 3600 },
  finish: { scope: "runs:finish", limit: 120, windowSec: 3600 },
  // Лист забега — четыре чтения из базы на открытие. Игрок листает десяток
  // последних забегов, а перебор чужих идентификаторов упрётся сюда раньше,
  // чем во что-то полезное: чужой забег всё равно не отдаётся.
  detail: { scope: "runs:detail", limit: 240, windowSec: 3600 },
  // Второй шанс за рекламу: вопрос «можно ли» на каждой смерти и забор по
  // досмотру. Больше двух сотен смертей в час не бывает и у самых быстрых.
  adContinue: { scope: "runs:continue-ad", limit: 240, windowSec: 3600 },
  // Второй шанс за самоцветы: цена на каждой смерти и сама покупка. Тот же
  // порядок, что у рекламного: честному игроку и двух сотен не нужно.
  gemContinue: { scope: "runs:continue-gems", limit: 240, windowSec: 3600 },
  // Рейтинг и профиль читают при открытии экранов: десять в минуту без
  // перерыва живому игроку не нужны, а скрипт упрётся сюда.
  leaderboard: { scope: "runs:leaderboard", limit: 600, windowSec: 3600 },
  profile: { scope: "runs:profile", limit: 600, windowSec: 3600 },
  // Запись для проверки: одна на забег, а повторы очереди клиента (нет сети,
  // таймаут) — единицы. Тридцать в минуту с запасом, скрипт упрётся сюда.
  proof: { scope: "runs:proof", limit: 30, windowSec: 60 },
};

