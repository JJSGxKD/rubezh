/**
 * Ссылки и упоминания в нике (tasks/T-0153, Р111): ник видят все в рейтинге и
 * «Друзьях», и он не должен рекламировать чужой канал или наше задание
 * «юзернейм бота в имени». Юзернейм бота уходит тем же правилом — как
 * `@упоминание`, отдельной константы нет.
 *
 * Зона голого домена — только из списка `TLDS`. Без списка любое «слово.слово»
 * стало бы ссылкой: «Mr.Smith», «Вася.Петя» и «х.у.й» (точки — разделители
 * словаря мата) пропали бы из ника или прошли мимо словаря. Новая зона — строка
 * в списке и тест.
 *
 * Порядок шагов важен: ссылки со схемой уходят целиком, голые домены — до
 * упоминаний, иначе из «a@mail.ru» и «t.me/@chan» упоминание вырезало бы
 * середину, а остаток домена остался бы в нике.
 */

const TLDS = [
  "com", "net", "org", "ru", "su", "рф", "io", "me", "ly", "gg", "tv", "cc", "xyz", "info", "biz", "app", "dev", "online", "site", "shop",
  "store", "club", "pro", "top", "vip", "link", "live", "fun", "ua", "by", "kz", "uz", "de", "uk", "us", "eu", "co", "to", "ws", "bot",
  "click", "work", "cloud", "space", "website", "tech", "art", "bet", "casino", "win", "ink", "one", "asia", "in", "cn", "fm", "am", "sh",
  "tk", "ml", "ga", "cf", "gq", "pw",
];

const SCHEME_LINK = /(?:https?|ftp):\/\/\S*/giu;
const WWW_LINK = /(?<![\p{L}\p{N}_])www\.\S+/giu;
/** Адрес почты слева необязателен, путь справа — тоже; после зоны не может идти буква, цифра, `_` и `-`. */
const BARE_DOMAIN = new RegExp(
  String.raw`(?:[\p{L}\p{N}_.+-]+@)?(?:[\p{L}\p{N}-]+\.)+(?:${TLDS.join("|")})(?![\p{L}\p{N}_-])(?:[/?#]\S*)?`,
  "giu",
);
/** `@` в начале или после не-буквы: «P@ssword» и «a@b» не трогаются, одинокая `@` уходит. */
const MENTION = /(?<![\p{L}\p{N}_])@[\p{L}\p{N}_]*/gu;

/** Ник без ссылок, голых доменов и упоминаний; пробелы на месте вырезанного остаются — их сворачивает вызывающий. */
export function stripLinksAndMentions(text: string): string {
  return text.replace(SCHEME_LINK, " ").replace(WWW_LINK, " ").replace(BARE_DOMAIN, " ").replace(MENTION, " ");
}
