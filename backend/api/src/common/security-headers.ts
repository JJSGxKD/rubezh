/**
 * Заголовки безопасности ответов API (docs/34-stage3-plan.md, WP3).
 *
 * API отдаёт только JSON, и заголовки подобраны под это: ответ никто не
 * должен ни встраивать, ни исполнять, ни кешировать. Ставятся до первых
 * денег, а не после — добавлять их к работающему платёжному контуру дороже,
 * чем к пустому (там же, Р12). Урок источника переноса: там блок заголовков
 * закомментирован целиком (docs/13-reuse-from-vpnsibcom.md §2.1 H).
 *
 * **Своими строками, а не `@fastify/helmet`.** Его умолчания рассчитаны на
 * HTML-приложение, и половину пришлось бы выключать, а вторую —
 * переопределять под JSON. Шесть заголовков в одном месте читаются проще, чем
 * конфигурация библиотеки, которая делает то же самое.
 *
 * **HSTS здесь нет намеренно.** API не знает, пришёл ли запрос по TLS: TLS
 * завершается на Caddy, и заголовок ставит он (docs/09-ci-cd.md §10).
 */
export const API_SECURITY_HEADERS: Readonly<Record<string, string>> = {
  // Браузер не угадывает тип по содержимому: JSON не станет скриптом.
  "x-content-type-options": "nosniff",
  // Ответ API не страница: ни загружать из него, ни встраивать его нечего.
  "content-security-policy": "default-src 'none'; frame-ancestors 'none'",
  // То же для старых клиентов, которые не знают frame-ancestors.
  "x-frame-options": "DENY",
  // Адрес запроса не уходит третьим лицам: в нём бывают параметры.
  "referrer-policy": "no-referrer",
  // Чужой сайт не прочитает ответ через <img> или <script>. Запросы из
  // Mini App идут через fetch с CORS, и их это не касается.
  "cross-origin-resource-policy": "same-site",
  // В ответах токены, профиль и рейтинг игрока — ни одному прокси и ни
  // одному кешу браузера хранить это незачем.
  "cache-control": "no-store",
};
