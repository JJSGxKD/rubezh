import type { EnemyPattern } from "@bh/shared-types";
import type { BenchMode } from "./metrics";

/** Профили фиксированной нагрузки — для сравнения двух сборок на одном числе. */
export const BENCH_POPULATIONS = [100, 200] as const;

/** Длительность прогона по умолчанию: короче — троттлинг не успевает начаться. */
export const BENCH_DEFAULT_DURATION_SEC = 180;

export const BENCH_DEFAULT_MODE: BenchMode = "ramp";

/**
 * Потолок роста в режиме нарастающей нагрузки.
 *
 * Это именно потолок, а не цель: при +2 врага в секунду за три минуты прогон
 * дойдёт примерно до 380. Потолок нужен, чтобы пул врагов не переполнился на
 * устройстве, которое так и не сломается.
 */
export const BENCH_DEFAULT_RAMP_CAP = 480;

/** Стартовая популяция в режиме нарастающей нагрузки. */
export const BENCH_RAMP_START = 20;

export interface StressPreset {
  addPerSecond: number;
  cap: number;
  maxEnemies: number;
  maxProjectiles: number;
  /** аварийный таймер: прогон обязан кончиться, даже если предел не найден */
  durationSec: number;
  weights: Partial<Record<EnemyPattern, number>>;
}

/**
 * Агрессивный прогон: ищем предел устройства, а не рабочий запас.
 *
 * Отличия от `ramp` и почему они такие:
 *
 * - **+20 врагов в секунду.** При +2 трёхминутный прогон упирается в конец
 *   времени, а не в производительность — именно это и произошло на первых
 *   замерах. Здесь за пять минут нагрузка доходит до нескольких тысяч.
 * - **Больше стрелков в смеси.** Снаряды — вторая ось нагрузки, и растёт она
 *   быстрее числа врагов: каждый стрелок добавляет свой поток объектов.
 *   Прогон без них меряет только половину картины.
 * - **Пулы на несколько тысяч.** Стандартных 512 хватает игре, но не поиску
 *   предела: прогон обязан упереться в устройство, а не в размер массива.
 * - **Пять минут — это аварийный таймер**, а не длительность прогона.
 *   Нормальный исход агрессивного режима — остановка по просадке.
 */
export const BENCH_STRESS: StressPreset = {
  addPerSecond: 20,
  cap: 4000,
  maxEnemies: 4096,
  maxProjectiles: 4096,
  durationSec: 300,
  weights: { swarm: 5, chase: 2, kite_and_shoot: 3 },
};
