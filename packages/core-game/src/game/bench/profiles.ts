/** Стартовая популяция стресс-теста: с неё нагрузка начинает расти. */
export const BENCH_RAMP_START = 20;

export interface StressPreset {
  addPerSecond: number;
  cap: number;
  maxEnemies: number;
  maxProjectiles: number;
  /** аварийный таймер: прогон обязан кончиться, даже если предел не найден */
  durationSec: number;
}

/**
 * Стресс-тест ищет предел устройства, а не рабочий запас.
 *
 * - **+20 врагов в секунду.** При +2 трёхминутный прогон упирался в конец
 *   времени, а не в производительность — именно это и произошло на первых
 *   замерах этапа 1. Здесь за пять минут нагрузка доходит до нескольких тысяч.
 * - **Пулы на несколько тысяч.** Стандартных 512 хватает игре, но не поиску
 *   предела: прогон обязан упереться в устройство, а не в размер массива.
 * - **Пять минут — это аварийный таймер**, а не длительность прогона.
 *   Нормальный исход — остановка по просадке.
 */
export const BENCH_STRESS: StressPreset = {
  addPerSecond: 20,
  cap: 4000,
  maxEnemies: 4096,
  maxProjectiles: 4096,
  durationSec: 300,
};
