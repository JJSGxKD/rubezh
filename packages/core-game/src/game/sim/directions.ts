/** Результат пишется в переданный объект: в горячем цикле новых объектов нет. */
export interface Direction {
  x: number;
  y: number;
}

export function createDirection(): Direction {
  return { x: 1, y: 0 };
}

/**
 * Сколько попыток делает отбор точки в круге. Ожидание — 1.27 попытки, но
 * бесконечный цикл в симуляции недопустим даже в теории: генератор конечен, и
 * гипотетическая длинная серия попаданий в угол квадрата не должна вешать
 * кадр. Исчерпали попытки — берём запасное направление, это детерминировано.
 */
const MAX_REJECTIONS = 8;

/** Равномерное направление по всему кругу. */
export function randomDirection(rng: Rng, out: Direction): void {
  for (let attempt = 0; attempt < MAX_REJECTIONS; attempt++) {
    const x = rng.nextRange(-1, 1);
    const y = rng.nextRange(-1, 1);
    const lengthSq = x * x + y * y;
    if (lengthSq > 1 || lengthSq < 1e-6) continue;

    const length = Math.sqrt(lengthSq);
    out.x = x / length;
    out.y = y / length;
    return;
  }
  out.x = 1;
  out.y = 0;
}

/**
 * Направление в дуге вокруг заданного. `arcSin` — синус половины раствора
 * дуги: 1 — вся передняя полуокружность, 0.5 — ±30°.
 *
 * `forwardX`/`forwardY` обязаны быть единичным вектором — нормировку делает
 * вызывающий код, у него она обычно уже посчитана.
 */
export function directionInArc(
  rng: Rng,
  forwardX: number,
  forwardY: number,
  arcSin: number,
  out: Direction,
): void {
  const lateral = rng.nextRange(-arcSin, arcSin);
  // Продольная доля добирается до единицы корнем: точка (along, lateral) в
  // базисе «вперёд + перпендикуляр» лежит ровно на единичной окружности.
  const along = Math.sqrt(Math.max(0, 1 - lateral * lateral));
  out.x = forwardX * along - forwardY * lateral;
  out.y = forwardY * along + forwardX * lateral;
}

/**
 * Направление на `step`-ю позицию кольца из `count` равномерных, начиная со
 * случайного поворота. Точное равенство углов не требуется — кольцо из
 * восемнадцати врагов вокруг игрока на глаз одинаково и при шаге таблицы.
 */
export function ringDirection(offset: number, step: number, count: number, out: Direction): void {
  const index = (offset + Math.round((step * TABLE_SIZE) / Math.max(1, count))) % TABLE_SIZE;
  const [x, y] = RING_TABLE[index];
  out.x = x;
  out.y = y;
}

/** Случайный поворот кольца: чтобы окружение не приходило всегда одинаково. */
export function randomRingOffset(rng: Rng): number {
  return rng.nextInt(0, TABLE_SIZE);
}
