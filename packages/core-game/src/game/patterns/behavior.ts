import type { World } from "../sim/world";

/**
 * Контракт паттерна поведения врага.
 *
 * `update` задаёт скорость врага и может стрелять, взрываться, менять фазу.
 * Перемещение по скорости, контактный урон и попадания снарядов — не его
 * дело, этим занимается шаг симуляции.
 *
 * `onDeath` вызывается, когда врага убил игрок, — уже после того, как слот
 * освобождён. Позиция в слоте ещё прежняя, но первый же спавн может занять
 * этот слот и перезаписать её: всё нужное читается в локальные переменные до
 * спавна.
 */
export interface PatternBehavior {
  update(world: World, index: number, dtSec: number): void;
  onDeath?(world: World, index: number): void;
}
