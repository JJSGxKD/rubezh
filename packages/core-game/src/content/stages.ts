//
// Три правила, по которым набраны числа ниже:
//
//  * ступень видна раньше, чем чувствуется: контур меняется сразу, а
//    здоровье и урон растут так, чтобы бой не переломился на одной минуте;
//  * опыт растёт быстрее здоровья — матёрый враг дороже стоит и лучше качает,
//    иначе выгоднее убегать от него к обычным;
//  * прежние ступени остаются в потоке: их вес не падает, добавляется вес
//    новой. Крыса первой минуты приходит и на десятой — рядом с матёрой.
//
// Элиты и мини-боссы ступеней не получают: они сами и есть контрольная точка
// сложности, и приходят событием в назначенную минуту.
