import type { ChestsDef } from "@bh/shared-types";

// Сундук забега — данные геймдизайнера (docs/39-retention-mechanics.md Б1,
// docs/35-stage4-plan.md Р102). Падает с каждой убитой элиты и босса,
// касанием выдаёт сразу несколько улучшений, без выбора. Числа стартовые:
// калибровка — по `pnpm balance:sim`, колонка «сундуков».
//
// Откуда берётся и что внутри — в CLAUDE.md, раздел «Как настроить сундук
// забега». Случайность сундука идёт отдельным потоком от seed забега, поэтому
// правка этих чисел не сдвигает ни карточки уровней, ни выпадение подборов.
export const CHESTS: ChestsDef = {
  // Первые четыре сундука заданы руками: новичок сначала видит маленький,
  // потом щедрый (3), потом снова скромный и только потом крупный. Рваный
  // ритм учит, что размер — сюрприз, и не даёт привыкнуть к «тройке».
  opening: [1, 3, 1, 5],

  // Дальше размер бросается по весам: одиночный сундук обычное дело, пятерной
  // — событие, от которого забег ощутимо меняется.
  sizes: [
    { size: 1, weight: 87 },
    { size: 3, weight: 10 },
    { size: 5, weight: 3 },
  ],

  // Босс — вершина забега, сундук с него не бывает пустячным.
  bossMinSize: 3,

  // Сундук должен усиливать то, что уже собрано: повышение взятого весит втрое
  // больше нового предмета, но новое всё ещё выпадает.
  ownedWeightMul: 3,

  // Запасная награда, когда улучшать нечего: ниже 70% здоровья — аптечка,
  // иначе опыт. Порог выше половины, потому что сундук берут и посреди боя.
  lowHpRatio: 0.7,

  // Запасной опыт — половина пути до следующего уровня: заметно, но не
  // обходит выбор карточек сразу за двумя уровнями.
  xpRatio: 0.5,

  // Больше двух сундуков на поле одновременно не нужно: третий означал бы,
  // что игрок уже бросил первые за радиус удержания.
  maxOnField: 2,
};
