import type { SiegeDef } from "@bh/shared-types";

/**
 * Осада стоящего (Р197, tasks/T-0392): рубеж берёт в осаду того, кто после третьей минуты долго
 * стоит в одном круге. Тому, кто двигается, осада не грозит.
 *
 * Как это читается в бою:
 * - с `fromSec` директор держит якорь — позицию игрока; пока игрок в круге `radius` вокруг якоря,
 *   копится счётчик, вышел — якорь переезжает на новое место, счётчик с нуля;
 * - за `warnSec` до конца отсчёта на земле загорается кольцо; отошёл — оно гаснет;
 * - дошло до `holdSec` — вокруг якоря встаёт строй стражей (`cordon`), а снаружи приходит кольцо
 *   элит, тех типов, которые таймлайн к этой секунде уже выпускал (как волна разлома Нави);
 * - после осады — перезарядка `cooldownSec`; каждая следующая осада сильнее прежней в `growth` раз,
 *   до уровня `maxLevel`; `calmSec` подряд вне осады снимают один уровень.
 *
 * Тайники с «законным» стоянием (капище, клад, древо-оберег) счётчик не копят. Пролога и «Лёгкой» осада
 * не касается.
 *
 * Числа откалиброваны сильным ботом (`pnpm balance:sim -t "сильный бот"`, docs/32-balance.md «Осада
 * стоящего»): «стоит» + «ветеран» держится 360–600 с, а у «бегает» медианы по профилям сдвигаются не
 * больше чем на 5%. Что важно знать правящему числа:
 * - `eliteCount: 0` — не случайность. Каждая элита осады роняет сундук, и сильный бот превращает осаду в
 *   добычу: с одной элитой стоящий живёт 830 с вместо 540, бегающий «средний» — на 60% дольше. Строй
 *   стражей угрожает только тому, кто не двигается; поэтому пока элиты выключены, механика и коридоры
 *   остаются, а решение о них — за геймдизайнером (docs/32-balance.md «Осада стоящего»);
 * - строй должен смыкаться: меньше полусотни стражей на кольце радиуса 260 оставляют бреши, и стоящий
 *   выходит через них, а потолок кольца — 64, поэтому `growth` и `maxLevel` малы: 56 → 60 → 64.
 */
export const SIEGE: SiegeDef = {
  fromSec: 180,
  radius: 160,
  holdSec: 25,
  warnSec: 4,
  cooldownSec: 20,
  calmSec: 60,
  growth: 1.07,
  maxLevel: 2,
  cordon: {
    enemy: "cordon_guard",
    count: 56,
    ring: { radius: 260, minRadius: 60, shrinkPerSec: 15, lifeSec: 60 },
  },
  eliteCount: 0,
};
