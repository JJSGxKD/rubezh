//
// Аптечка подбирается касанием и только при неполном здоровье: с полным она
// остаётся лежать, и игрок сам решает, когда за ней вернуться. Шанс с рядового
// врага маленький — около одной аптечки на восемьдесят убийств, — а элита
// роняет её всегда.
//
// Магнит притягивает все кристаллы на поле, динамит взрывается вокруг игрока:
// рядовых выкашивает, элите снимает долю здоровья, но не убивает. Оба реже
// аптечки — это событие забега, а не расходник.
