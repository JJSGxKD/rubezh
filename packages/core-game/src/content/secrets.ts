// идти: капище, клад, камень-указатель и огонёк. Очков рейтинга они не дают —
// дают силу, иначе топ решало бы везение раскладки. Числа стартовые:
// калибровка — по `pnpm balance:sim`.
//
// Что делает каждый вид и как настроить — в CLAUDE.md, раздел «Как настроить
// тайники». Позиции и виды бросаются из собственного потока случайности от
// seed забега, поэтому правка этих чисел не сдвигает ни карточки уровней, ни
// выпадение подборов, ни сундуки врагов.
//
// Расстояния и радиусы — в игровых единицах, как скорости врагов; скорость
// огонька — единиц в секунду.
