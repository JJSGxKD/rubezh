  // неоткрытому тайнику. Скорость ниже скорости бега игрока
  // (190): за огоньком можно идти, не теряя его из виду, и его нельзя обогнать.
  wisp: { appearSec: 90, speed: 80 },

  // Благословения — прибавки на весь забег тем же языком, что у снаряжения и
