/**
 * Целевые коридоры баланса (docs/26-stage2-plan.md, WP4.6).
 *
 * Зафиксированы **до** калибровки и намеренно: иначе «цель» подгоняется под
 * то, что получилось, и перестаёт быть целью. Числа предложены по ориентиру
 * 6–10 минут забега живого игрока (docs/05-game-design.md §1) и **ждут
 * подтверждения геймдизайнера** — правит их он, здесь и в §4.6 плана.
 *
 * Плоские поля описывают главный бой — «Сложную» (Р126). Давление после
 * 8-й минуты — блок `latePressure`. Коридора обучающей «Лёгкой» нет: первый
 * забег новичка — пролог (Р179), а не бот-уклонист.
 *
 * Коридоры заданы для ботов, а не для людей: бот — грубая модель, его забег
 * короче человеческого, потому что он не выбирает билд и не читает поле. Живой
 * ориентир проверяется ручным плейтестом, а не тестом в CI.
 */
export const BALANCE_TARGETS = {
  /**
   * Пассивный бот обязан умереть: бесконечный забег без действий означает, что
   * играть незачем. Порог короткий — на первой минуте ещё почти нет угрозы,
   * так что минута с небольшим и есть предел терпимого.
   */
  passiveDeathBeforeSec: 90,

  /**
   * Уклоняющийся бот: медиана выживания в этом коридоре. Нижняя граница —
   * «живёт не меньше предела пассивного», верхняя — «Сложная» по боту не
   * легче половины обучающей.
   */
  dodgingMedianSec: { min: 90, max: 300 },

  /**
   * Доля забегов уклоняющегося бота, оборвавшихся до минуты. Первая минута —
   * это знакомство: игрок, умерший в ней, не успел понять, во что играет.
   */
  dodgingDeathsBeforeMinuteRatioMax: 0.2,

  /**
   * Когда приходит первый выбор улучшения. Пустое начало без решений — самый
   * дешёвый способ потерять игрока, а слишком ранний выбор он не успевает
   * прочитать.
   */
  firstLevelUpSec: { min: 3, max: 30 },

  /**
   * Секунда первого события элиты или босса в таймлайне: с неё падает первый
   * сундук. Раньше минуты игрок ещё не освоился, позже двух — большинство
   * бот-забегов умирает до сундука (docs/39-retention-mechanics.md §3).
   */
  firstChestEventSec: { min: 60, max: 120 },

  /**
   * Давление после 8-й минуты (Р128). Бот до неё не доживает, поэтому оно
   * проверяется свойствами контента, а не смертностью бота.
   */
  latePressure: {
    fromSec: 480,
    toSec: 1200,
    /** во сколько раз индекс силы врага растёт за три минуты, на точках 8:00 → 11:00 → 14:00 → 17:00 */
    strengthGrowthPer3Min: { min: 1.5, max: 3.2 },
    /** событий элит и боссов в минуту между fromSec и toSec */
    rankEventsPerMinuteMin: 0.9,
    /** во сколько раз плотнее, чем до fromSec */
    rankEventsDensityRatioMin: 2,
    /** сколько множителей «Сложной» можно поднять: потолок живых × 240 ≤ 360 */
    hardMaxAliveMulMax: 1.5,
  },
} as const;

/**
 * Во сколько раз эволюция сильнее последнего уровня базового оружия, по силе
 * `урон · снаряды / пауза` (tasks/T-0102, docs/32-balance.md). Ниже нижней
 * границы эволюции не за что хотеть, выше верхней — она ломает таймлайн.
 */
export const EVOLUTION_POWER_RATIO = { min: 1.8, max: 3.5 } as const;

/**
 * Сборка набора (T-0193, Р127): когда бессмертный бот на «Сложной» доводит
 * все слоты до максимума. Коридор **относительный**, а не в секундах: бот не
 * человек, он собирает набор за 1000–2500 с, а живой игрок — за ≈ 8 минут, и
 * секунды бота с минутами человека не сравниваются. Цель Р127 — «набор
 * собирается с 8-й до 15-й минуты», то есть примерно вдвое позже: у того же
 * бота это ×1,6…×2,3 к замеру до правок.
 *
 * Лежит отдельно от `BALANCE_TARGETS`: это ориентир прогона `pnpm balance:sim`,
 * а не часть контента, которую правит редактор баланса и которая уезжает в
 * снимок.
 */
export const BUILD_COMPLETE_TARGETS = {
  /**
   * Медиана секунды сборки до правок T-0193: бессмертный бот («dodging», `godMode`),
   * «Сложная», оружие «Искра», 20 seed, контент dev от 01.11.2026 (слоты 3/2/1/1,
   * навыки по 4–5 уровней, кривая 1,22). Собрали все двадцать: p10 601 с, p90 1058 с.
   */
  buildCompleteBaselineSec: 685.5,
  /** во сколько раз позже базы собирается набор после правок */
  buildCompleteRatio: { min: 1.6, max: 2.3 },
  /** не менее такой доли seed обязана собрать набор до `max × buildCompleteHorizon` секунд */
  buildCompleteShareMin: 0.6,
  /** запас потолка прогона к верхней границе коридора */
  buildCompleteHorizon: 1.15,
} as const;

/** Границы коридора сборки в секундах: база × доли из `BUILD_COMPLETE_TARGETS`. */
export function buildCompleteCorridorSec(): { min: number; max: number } {
  const { buildCompleteBaselineSec, buildCompleteRatio } = BUILD_COMPLETE_TARGETS;
  return { min: buildCompleteBaselineSec * buildCompleteRatio.min, max: buildCompleteBaselineSec * buildCompleteRatio.max };
}

/**
 * Подстройка под силу (Р131, Р183, T-0196): коридоры калибровки трёх профилей
 * силы (`POWER_PROFILES`) и слабого устройства. Все медианы — уклоняющегося бота
 * на «Сложной», стартовые оружия первого уровня аккаунта, те же seed, что у
 * остальных сценариев.
 *
 * Зафиксированы **до** калибровки и не двигаются вместе с числами контента.
 * Бот слабее человека, поэтому коридоры заданы отношениями медиан профилей, а не
 * минутами: цель Р183 — лесенка около 7, 10 и 14 минут у настоящих игроков
 * (каждая ступень силы ≈ +40% жизни) — сверяется по аналитике после выката.
 * Бота без набора с профилями не сравниваем: снаряжение усиливает бота примерно
 * в семь раз, и это сравнение ничего не говорит о подстройке.
 * Лежат отдельно от `BALANCE_TARGETS`, как коридор сборки: это ориентир прогона
 * `pnpm balance:sim` и теста, а не часть контента, которая уезжает в снимок и
 * меняет его отпечаток.
 */
export const PRESSURE_TARGETS = {
  /** «новичок» к «среднему»: цель 0,7 = 7 / 10 минут */
  noviceToAverage: { min: 0.65, max: 0.8 },
  /** «полный арсенал» к «среднему»: цель 1,4 = 14 / 10 минут */
  fullToAverage: { min: 1.25, max: 1.6 },
  /** «средний» на слабом устройстве к «среднему» на обычном: слабый телефон не должен жить меньше */
  lightToStandard: { min: 0.85, max: 1.15 },
  /**
   * Запас пика врагов на слабом устройстве сверх `caps.light` и самого крупного
   * события таймлайна: потолок держит поток, события его не режут, а делящиеся
   * после распада добавляют ещё немного.
   */
  lightPeakSlack: 8,
  /** если на обычном пик не ниже такой доли `caps.light`, на слабом он не больше `lightPeakShareMax` от обычного */
  lightPeakThreshold: 1.25,
  lightPeakShareMax: 0.8,
  /** уровни давления `L` на старте профилей */
  levels: {
    novice: { min: 0.76, max: 0.85 },
    average: { min: 0.9, max: 1.1 },
    full: { min: 1.2, max: 1.3 },
  },
} as const;
