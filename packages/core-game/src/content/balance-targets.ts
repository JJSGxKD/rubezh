/**
 * Целевые коридоры баланса (docs/26-stage2-plan.md, WP4.6).
 *
 * Зафиксированы **до** калибровки и намеренно: иначе «цель» подгоняется под
 * то, что получилось, и перестаёт быть целью. Числа предложены по ориентиру
 * 6–10 минут забега живого игрока (docs/05-game-design.md §1) и **ждут
 * подтверждения геймдизайнера** — правит их он, здесь и в §4.6 плана.
 *
 * Плоские поля описывают главный бой — «Сложную» (Р126). Обучающая «Лёгкая»
 * живёт блоком `tutorial`, давление после 8-й минуты — блоком `latePressure`.
 *
 * Коридоры заданы для ботов, а не для людей: бот — грубая модель, его забег
 * короче человеческого, потому что он не выбирает билд и не читает поле. Живой
 * ориентир проверяется ручным плейтестом, а не тестом в CI.
 */
export const BALANCE_TARGETS = {
  /**
   * Пассивный бот обязан умереть: бесконечный забег без действий означает, что
   * играть незачем. Порог короткий — на первой минуте ещё почти нет угрозы,
   * так что минута с небольшим и есть предел терпимого.
   */
  passiveDeathBeforeSec: 90,

  /**
   * Уклоняющийся бот: медиана выживания в этом коридоре. Нижняя граница —
   * «живёт не меньше предела пассивного», верхняя — «Сложная» по боту не
   * легче половины обучающей.
   */
  dodgingMedianSec: { min: 90, max: 300 },

  /**
   * Доля забегов уклоняющегося бота, оборвавшихся до минуты. Первая минута —
   * это знакомство: игрок, умерший в ней, не успел понять, во что играет.
   */
  dodgingDeathsBeforeMinuteRatioMax: 0.2,

  /**
   * Когда приходит первый выбор улучшения. Пустое начало без решений — самый
   * дешёвый способ потерять игрока, а слишком ранний выбор он не успевает
   * прочитать.
   */
  firstLevelUpSec: { min: 3, max: 30 },

  /**
   * Секунда первого события элиты или босса в таймлайне: с неё падает первый
   * сундук. Раньше минуты игрок ещё не освоился, позже двух — большинство
   * бот-забегов умирает до сундука (docs/39-retention-mechanics.md §3).
   */
  firstChestEventSec: { min: 60, max: 120 },

  /** Обучающий первый забег — «Лёгкая»: коридоры прежние, бот — тот же. */
  tutorial: {
    dodgingMedianSec: { min: 150, max: 480 },
    dodgingDeathsBeforeMinuteRatioMax: 0.2,
  },

  /**
   * Давление после 8-й минуты (Р128). Бот до неё не доживает, поэтому оно
   * проверяется свойствами контента, а не смертностью бота.
   */
  latePressure: {
    fromSec: 480,
    toSec: 1200,
    /** во сколько раз индекс силы врага растёт за три минуты, на точках 8:00 → 11:00 → 14:00 → 17:00 */
    strengthGrowthPer3Min: { min: 1.5, max: 3.2 },
    /** событий элит и боссов в минуту между fromSec и toSec */
    rankEventsPerMinuteMin: 0.9,
    /** во сколько раз плотнее, чем до fromSec */
    rankEventsDensityRatioMin: 2,
    /** сколько множителей «Сложной» можно поднять: потолок живых × 240 ≤ 360 */
    hardMaxAliveMulMax: 1.5,
  },
} as const;

/**
 * Во сколько раз эволюция сильнее последнего уровня базового оружия, по силе
 * `урон · снаряды / пауза` (tasks/T-0102, docs/32-balance.md). Ниже нижней
 * границы эволюции не за что хотеть, выше верхней — она ломает таймлайн.
 */
export const EVOLUTION_POWER_RATIO = { min: 1.8, max: 3.5 } as const;
