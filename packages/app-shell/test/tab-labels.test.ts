import { describe, expect, it } from "vitest";
import { tabLabelMode } from "../src/design-system/components/tab-labels";

// Подписи нижней панели: у всех вкладок, если каждая помещается с запасом
// 4 px с каждой стороны, иначе только у активной. Правило — по измерению, а не
// по порогу ширины: шрифт и язык сменятся.

const LABELS = [49, 49, 46, 49, 47, 42];

describe("режим подписей нижней панели", () => {
  it("панель 360 px: подписи помещаются — у всех", () => {
    expect(tabLabelMode(LABELS, [59, 59, 59, 59, 59, 59])).toBe("all");
  });

  it("граница: подпись 51 при вкладке 59 ещё помещается (51 + 8 = 59)", () => {
    expect(tabLabelMode([51], [59])).toBe("all");
  });

  it("одна подпись 52 при вкладках по 59 — только у активной", () => {
    expect(tabLabelMode([49, 52, 46, 49, 47, 42], [59, 59, 59, 59, 59, 59])).toBe("active");
  });

  it("панель 320 px: вкладки по 53 — только у активной", () => {
    expect(tabLabelMode(LABELS, [53, 53, 53, 53, 53, 53])).toBe("active");
  });

  it("пустые массивы — только у активной", () => {
    expect(tabLabelMode([], [])).toBe("active");
  });

  it("ширина вкладки 0 (панель не разложена или скрыта) — только у активной", () => {
    expect(tabLabelMode([49, 49], [59, 0])).toBe("active");
  });

  it("длины массивов различаются — только у активной", () => {
    expect(tabLabelMode([49, 49, 46], [59, 59])).toBe("active");
  });
});
